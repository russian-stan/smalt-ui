import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath, URL } from 'node:url'

/**
 * Collects public component names from the src/components/* folders and provider names from
 * src/providers/*, and writes them to src/component-names.ts. The file is committed: it is used by
 * the unplugin-vue-components resolver and the Nuxt module, which cannot import Vue code (they run
 * in Node during the consumer's build).
 */
const root = fileURLToPath(new URL('../src', import.meta.url))

const dirs = (path) =>
  readdirSync(path, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()

const components = dirs(`${root}/components`)
const providers = dirs(`${root}/providers`)

/**
 * The format matches Prettier (singleQuote, trailing comma): otherwise the generated file fails
 * `prettier --check`, and `pnpm format` does not help because the next prebuild rewrites it.
 */
const PRINT_WIDTH = 100

const asList = (items, declaration) => {
  const inline = `[${items.map((item) => `'${item}'`).join(', ')}]`
  // Prettier keeps an array on one line while it fits in printWidth.
  if (`${declaration}${inline} as const`.length <= PRINT_WIDTH) return inline
  return `[\n${items.map((item) => `  '${item}',`).join('\n')}\n]`
}

const out = `// Generated by scripts/gen-component-names.mjs. Do not edit by hand.

/** Public component names (\`SButton\`, \`SInput\`, …). */
export const COMPONENT_NAMES = ${asList(components, 'export const COMPONENT_NAMES = ')} as const

/** Public provider names (\`ToastProvider\`, \`ConfigProvider\`). */
export const PROVIDER_NAMES = ${asList(providers, 'export const PROVIDER_NAMES = ')} as const

/** Providers with an "explicit import only" policy; they are not registered automatically. */
export const EXPLICIT_ONLY_PROVIDERS = ['ConfigProvider'] as const
`

writeFileSync(`${root}/component-names.ts`, out)
console.log(`component-names.ts: ${components.length} components, ${providers.length} providers`)

/**
 * The Nuxt module is built as a separate package and does not import core's Vue code, so it gets
 * its own copy of the same list.
 */
const nuxtOut = fileURLToPath(new URL('../../nuxt/src/component-names.ts', import.meta.url))
writeFileSync(nuxtOut, out)
console.log('component-names.ts copied to packages/nuxt/src')
